/**
 * 道路の斜め接続の可否（実装書 §6・D3）。
 *
 * **描画（`src/render/gameScene.ts`）と経路探索（`pathfind.ts`）が必ず同じ規則を使うこと。**
 * 別々に持つと「画面には無い道を車が走る」「繋がって見えるのに経路が見つからない」が起きる。
 *
 * ## なぜ規則が要るか
 *
 * D3 で道路グラフを8方向接続にしたのは、**斜めに引いた道（階段状のタイル列）を
 * 道路として機能させるため**だった。しかし「隣接する2タイルが斜めなら常に繋ぐ」と
 * すると、十字路で困ったことが起きる:
 *
 * ```
 *      N            N は中心の上、W は中心の左。この2つは**互いに斜め隣接**なので
 *    W C E          斜めの接続が引かれる。四方の腕すべてで同じことが起きるため、
 *      S            交差点が「十字」ではなく**菱形**に描かれ、隙間の三角形が残る。
 * ```
 *
 * 経路探索も同じ8方向なので、車は実際にこの斜め（コスト √2 ≒ 1.41）を通る。
 * 中心を経由する 2 より安いためで、**交差点に入らず角を斜めに横切る**動きになる。
 *
 * ## 規則
 *
 * **斜めの接続が成立するのは、共有する2つの直交隣接タイルの「どちらも道路でない」ときだけ。**
 *
 * - 階段状の斜め道路（周りに道路が無い）→ 成立する。D3 の目的は保たれる
 * - 十字路の腕どうし（中心が道路）→ 成立しない。交差点をきちんと通る
 * - 2×2 の塊（両方が道路）→ 成立しない。直交だけで繋がるので迂回不要
 *
 * **連結性は絶対に失われない。** 斜めを落とすのは共有する直交隣接のどちらかが道路のときだけで、
 * そのときは必ず「直交2手」の代替経路が存在する（(x,y)→(x+dx,y)→(x+dx,y+dy)）。
 * したがって行けなくなる場所は生まれず、増えるコストは高々 2 − √2 ≒ 0.59 / 回。
 */

/**
 * `(x, y)` から `(x+dx, y+dy)` への斜め移動が許されるか。
 *
 * `isRoad` は「そのタイルが道路か」を返す述語。実際のグリッドでも、
 * ドラッグ中のプレビュー（まだ敷かれていないタイル集合）でも使えるように関数で受け取る。
 * `dx` / `dy` はどちらも 0 でないこと（直交の呼び出しでは使わない）。
 */
export function diagonalAllowed(
  isRoad: (x: number, y: number) => boolean,
  x: number,
  y: number,
  dx: number,
  dy: number,
): boolean {
  return !isRoad(x + dx, y) && !isRoad(x, y + dy);
}
